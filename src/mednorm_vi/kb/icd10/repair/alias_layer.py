"""Governed Vietnamese alias layer for the ICD-10 KB (Audit 0068 §5).

The competition ICD index carried **zero** populated alias lists across 15,308 concepts,
while RxNorm carried 82,429. That gap is why a mention like *ung thư tụy* could not reach
C25, whose only searchable text is *u ác tính ở tụy* - the same disease in different
clinical register.

Every alias here is derived deterministically from a governed title by an explicit,
reviewable rule. Nothing is generated by a model, nothing comes from public-test text, and
the Audit-0067 AI consensus is not used as an authority for any new medical mapping - it
only told us where to look.

The rule table is deliberately small. A transformation is included only when it preserves
concept semantics for every code it can apply to; anything that could change meaning
(laterality, acuity, site) is excluded by construction.
"""

from __future__ import annotations

import re
import unicodedata
from dataclasses import dataclass
from typing import Any

ALIAS_CANONICAL = "canonical_title"
ALIAS_SYNONYM_RULE = "synonym_rule"
ALIAS_PUNCTUATION = "punctuation_variant"
ALIAS_UNACCENTED = "unaccented_variant"

CONFIDENCE_SOURCE = "source_exact"
CONFIDENCE_DERIVED = "rule_derived"

#: Reviewed Vietnamese clinical register variants. Each pair names the same concept in
#: Vietnamese medical usage; none encodes site, laterality, acuity or severity, so applying
#: one cannot change which ICD concept a title denotes.
SYNONYM_RULES: tuple[tuple[str, str, str], ...] = (
    ("u ác tính", "ung thư", "malignant neoplasm / cancer, equivalent clinical register"),
    ("u ác tính", "bướu ác tính", "regional Vietnamese variant for malignant tumour"),
    ("ung thư", "u ác tính", "reverse of the cancer/malignant-neoplasm pair"),
    ("u lành", "u lành tính", "benign neoplasm, expanded form"),
    ("viêm phổi", "viêm phế quản phổi", ""),  # excluded below; kept to document rejection
)

#: Pairs deliberately NOT applied. Recorded so the exclusion is visible and auditable
#: rather than silently absent: each changes the anatomical or pathological claim.
REJECTED_RULES: tuple[tuple[str, str, str], ...] = (
    ("viêm phổi", "viêm phế quản phổi", "bronchopneumonia is a distinct entity, not a synonym"),
    ("bệnh", "hội chứng", "disease and syndrome are not interchangeable"),
    ("cấp", "mạn", "acuity is a coded distinction"),
)

_APPLIED_RULES = tuple(r for r in SYNONYM_RULES if r[2])

_PUNCT = re.compile(r"[\[\]()+*†‡]")
_SPACE = re.compile(r"\s+")


def strip_accents(value: str) -> str:
    decomposed = unicodedata.normalize("NFD", value)
    without = "".join(c for c in decomposed if unicodedata.category(c) != "Mn")
    return without.replace("đ", "d").replace("Đ", "D")


def normalize_spacing(value: str) -> str:
    return _SPACE.sub(" ", _PUNCT.sub(" ", value)).strip()


@dataclass(frozen=True, slots=True)
class Alias:
    code: str
    alias: str
    alias_type: str
    source: str
    rule: str
    confidence: str

    def as_dict(self) -> dict[str, Any]:
        return {
            "code": self.code,
            "alias": self.alias,
            "alias_type": self.alias_type,
            "source": self.source,
            "transformation_rule": self.rule,
            "confidence": self.confidence,
        }


def aliases_for(code: str, title: str, *, source: str) -> list[Alias]:
    """Every governed alias derivable from one clean title.

    Returns an empty list for an unusable title: an alias built from an ICD instruction
    would be worse than no alias, because it would make the damaged text *more* reachable.
    """
    from .title_recovery import is_damaged_title

    if not title or is_damaged_title(title):
        return []

    out: list[Alias] = [
        Alias(code, title.strip(), ALIAS_CANONICAL, source, "", CONFIDENCE_SOURCE)
    ]
    seen = {title.strip().casefold()}

    def add(text: str, alias_type: str, rule: str, confidence: str) -> None:
        candidate = text.strip()
        if candidate and candidate.casefold() not in seen:
            seen.add(candidate.casefold())
            out.append(Alias(code, candidate, alias_type, source, rule, confidence))

    spaced = normalize_spacing(title)
    add(spaced, ALIAS_PUNCTUATION, "punctuation and bracket normalisation", CONFIDENCE_DERIVED)

    lowered = title.casefold()
    for source_form, target_form, description in _APPLIED_RULES:
        if source_form in lowered:
            replaced = re.sub(re.escape(source_form), target_form, title, flags=re.IGNORECASE)
            add(replaced, ALIAS_SYNONYM_RULE, f"{source_form} -> {target_form}: {description}",
                CONFIDENCE_DERIVED)
            add(normalize_spacing(replaced), ALIAS_SYNONYM_RULE,
                f"{source_form} -> {target_form} (spacing normalised)", CONFIDENCE_DERIVED)

    # Unaccented forms are an ADDITIONAL channel, never a replacement: collapsing accents
    # is what let `sởi` (measles) match `sỏi` (calculus) in Audit 0067.
    for existing in list(out):
        add(strip_accents(existing.alias), ALIAS_UNACCENTED,
            "accent-stripped search variant (secondary channel only)", CONFIDENCE_DERIVED)
    return out


