"""Deterministic recovery of Vietnamese ICD-10 titles from the governed source (Audit 0068).

Audit 0067 found that ~18% of ICD concepts in the competition index carry an ICD *tabular
instruction* where their title should be - rectal cancer (C20) is stored as
`Bao gồm: Bóng` ("Includes: …"), measles (B05) as `- Bao gồm: bệnh`. No retriever can match
a Vietnamese mention against text like that, which is why coverage failures outnumbered
ranking failures 13.5 : 1.

The damage is NOT in the index build: the derived CSV carries the same corrupted strings.
It is a column-selection defect in the original PDF row parser. Each source row lays out

    … <undotted code> <english title> <english note> <vietnamese title> <vietnamese note>

and the parser captured the Vietnamese *note* rather than the Vietnamese *title*. Both are
present in the governed TT06-2026 source, so recovery is a re-read of local evidence, not
an invention: **no title here is generated by a model.**

Everything is deterministic and provenance-carrying. A recovered title is only accepted
when it is a plain title - a string that starts with an instruction marker can never
replace one.
"""

from __future__ import annotations

import re
import unicodedata
from dataclasses import dataclass
from typing import Any

#: Markers that make a string an ICD tabular note rather than a concept title. Checked
#: after stripping leading list glyphs, because the source renders notes as "- Bao gồm: …".
NOTE_MARKERS: tuple[str, ...] = (
    "bao gồm",
    "loại trừ",
    "incl.",
    "excl.",
    "includes",
    "excludes",
    "lưu ý",
    "tham khảo",
    "ghi chú",
    "chú ý",
    "note:",
)

_LEADING_GLYPHS = re.compile(r"^[\s\-+*†‡•·\[\]()]+")
_CODE_TOKEN = re.compile(r"^[A-Z]\d{2}(\.\d+)?[†*]?$")
_SEQ_TOKEN = re.compile(r"^\d+(\s+[IVXLC]+)?$")
_COLUMN_SPLIT = re.compile(r"\s{2,}")
_ROW_START = re.compile(r"^\s*(\d+)\s+([IVXLC]+)\s")


def strip_glyphs(value: str) -> str:
    return _LEADING_GLYPHS.sub("", value or "").strip()


def is_note(value: str) -> bool:
    """True when the string is an ICD instruction rather than a concept title."""
    bare = strip_glyphs(value).casefold()
    return any(bare.startswith(marker) for marker in NOTE_MARKERS)


def has_vietnamese_diacritic(value: str) -> bool:
    """Vietnamese-specific letters, used to separate the VI column from the EN one."""
    decomposed = unicodedata.normalize("NFD", value or "")
    if any(unicodedata.category(ch) == "Mn" for ch in decomposed):
        return True
    return any(ch in "đĐ" for ch in value or "")


def is_damaged_title(value: str) -> bool:
    """The Audit-0067 damage conditions, as one predicate.

    A title is damaged when it is an instruction, ends mid-phrase, or is too short to be a
    concept name. Deliberately conservative: a clean title is never rewritten for style.
    """
    text = (value or "").strip()
    if not text:
        return True
    if is_note(text):
        return True
    if text.rstrip().endswith((",", ":", "(", "-", "+", "/")):
        return True
    return len(strip_glyphs(text)) <= 6


@dataclass(frozen=True, slots=True)
class RecoveredTitle:
    """One repaired concept, with everything needed to justify the change."""

    code: str
    previous_title: str
    recovered_title: str
    english_title: str
    source_field: str
    source_row: int
    reason: str

    def as_dict(self) -> dict[str, Any]:
        return {
            "code": self.code,
            "previous_canonical_name": self.previous_title,
            "repaired_canonical_name": self.recovered_title,
            "english_title": self.english_title,
            "source_field": self.source_field,
            "source_row": self.source_row,
            "reason": self.reason,
        }


def split_columns(line: str) -> list[str]:
    return [c.strip() for c in _COLUMN_SPLIT.split(line.strip()) if c.strip()]


def normalize_code(value: str) -> str:
    """Strip dots and dagger/asterisk glyphs so `B05.0†` and `B050` compare equal."""
    return (value or "").replace(".", "").rstrip("†*").strip()


def concept_anchor(columns: list[str], code: str) -> int:
    """Index of the row's OWN undotted-code column, or -1.

    A category code such as `B05` also appears in every one of its subcodes' rows, so
    matching the token anywhere reads a child's title into the parent. The concept's own
    row is identified by the adjacent pair `<dotted code> <undotted code>`: in the B05 row
    that is `B05 B05`, in the B05.0 row `B05.0† B050`. Requiring the pair is what stops a
    parent inheriting `Bệnh sởi kèm biến chứng` from a child.
    """
    for index in range(len(columns) - 1, 0, -1):
        if columns[index].strip() != code:
            continue
        if normalize_code(columns[index - 1]) == code:
            return index
    # Fallback for a layout artifact: pdftotext sometimes glues the dotted-code column
    # onto wrapped title text, e.g. `U ác tính ở trực C20` followed by `C20`. Requiring the
    # previous column to END with the code keeps the pairing requirement - and therefore
    # keeps a parent from reading a child's row - while tolerating the merge.
    for index in range(len(columns) - 1, 0, -1):
        if columns[index].strip() != code:
            continue
        if normalize_code(columns[index - 1]).endswith(code):
            return index
    return -1


def titles_from_row(columns: list[str], code: str) -> tuple[str, str]:
    """(vietnamese_title, english_title) for ``code`` from its own source row.

    Note columns and bare code tokens are discarded; the last Vietnamese-script title is
    the Vietnamese name and the first non-Vietnamese title is the English name.
    """
    anchor = concept_anchor(columns, code)
    if anchor < 0:
        return "", ""

    candidates = [
        column
        for column in columns[anchor + 1 :]
        if column
        and not _CODE_TOKEN.match(column.strip())
        and not _SEQ_TOKEN.match(column.strip())
        and not is_note(column)
    ]
    vietnamese = ""
    english = ""
    for column in candidates:
        if has_vietnamese_diacritic(column):
            vietnamese = column
        elif not english:
            english = column
    return _strip_english_prefix(vietnamese).strip(), english.strip()


#: English instruction fragments the layout sometimes glues onto the Vietnamese column.
_ENGLISH_LEAKS = re.compile(
    r"^(use additional code[^A-ZĐ]*|code first[^A-ZĐ]*|note[: ][^A-ZĐ]*)", re.IGNORECASE
)


def _strip_english_prefix(value: str) -> str:
    """Drop a leaked English instruction prefix from a Vietnamese title column."""
    return _ENGLISH_LEAKS.sub("", value or "").strip()


def recover_titles(
    text_lines: list[str], targets: dict[str, str]
) -> tuple[dict[str, RecoveredTitle], dict[str, str]]:
    """Recover a Vietnamese title for every damaged code in ``targets``.

    ``targets`` maps undotted code -> its current (damaged) canonical name. Returns the
    accepted repairs and, separately, the codes that could not be recovered - the second
    value is what decides whether the governed source is sufficient.
    """
    rows: list[tuple[int, list[str]]] = [
        (number, split_columns(line))
        for number, line in enumerate(text_lines, start=1)
        if _ROW_START.match(line)
    ]
    # One row belongs to exactly one concept: the one whose dotted/undotted pair it carries.
    by_code: dict[str, list[tuple[int, list[str]]]] = {}
    for number, columns in rows:
        for index in range(1, len(columns)):
            token = columns[index].strip()
            if not token or not _CODE_TOKEN.match(token):
                continue
            previous = normalize_code(columns[index - 1])
            if previous == token or previous.endswith(token):
                by_code.setdefault(token, []).append((number, columns))
                break

    recovered: dict[str, RecoveredTitle] = {}
    unrecovered: dict[str, str] = {}
    for code, previous in targets.items():
        best: tuple[str, str, int] | None = None
        for number, columns in by_code.get(code, []):
            vietnamese, english = titles_from_row(columns, code)
            if vietnamese and not is_damaged_title(vietnamese):
                if best is None or len(vietnamese) > len(best[0]):
                    best = (vietnamese, english, number)
        if best is None:
            unrecovered[code] = previous
            continue
        vietnamese, english, number = best
        recovered[code] = RecoveredTitle(
            code=code,
            previous_title=previous,
            recovered_title=vietnamese,
            english_title=english,
            source_field="vietnamese_title_column",
            source_row=number,
            reason="previous name was an ICD tabular note or truncated fragment",
        )
    return recovered, unrecovered


